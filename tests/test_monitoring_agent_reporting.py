def test_historical_evidence_and_hypotheses_are_visibly_separate():
    evaluation = evaluate_incident_lifecycle(
        [_cycle(1, transport={"system_runtime": "schema_error"}, historical=True)]
    )
    snapshot = build_monitoring_report_snapshot(
        generated_at=BASE_TIME,
        incident_evaluation=evaluation,
        evidence_gaps=("heartbeat_transition_history_not_persisted",),
        historical_notes=("0.7 to 0.8.1 migration created planned stop evidence",),
        hypotheses=("target process restart timing requires later operator review",),
    )

    report = render_monitoring_report(snapshot)

    assert "## Rule conclusions" in report
    assert (
        "## Historical qualifications\n"
        "- [info] historical note: 0.7 to 0.8.1 migration created planned stop "
        "evidence"
    ) in report
    assert (
        "- [warning] historical-only observer_self_health:facade_contract: "
        "action=suppressed"
    ) in report
    assert (
        "## Hypotheses / not yet verified\n"
        "- [info] hypothesis: target process restart timing requires later "
        "operator review"
    ) in report


def test_programming_agent_prompt_is_draft_only_bounded_and_non_authorizing():
    snapshot = build_monitoring_report_snapshot(
        generated_at=BASE_TIME,
        incident_evaluation=_empty_evaluation(),
        latest_heartbeat_status="healthy",
        observation_count=9,
        transport_failure_count=0,
    )

    prompt = render_programming_agent_prompt(snapshot, max_chars=4_000)

    assert prompt.startswith(DRAFT_PROMPT_LINE)
    assert "Propose diagnostics and success criteria; do not perform them." in prompt
    assert (
        "No command execution, network contact, state mutation, service restart, "
        "delivery attempt, or alert replacement is authorized."
    ) in prompt
    assert "summary_status: healthy" in prompt
    assert "delivery_enabled=false" in prompt
    assert len(prompt) <= 4_000


def test_report_and_prompt_redact_secrets_paths_queries_and_private_ids():
    snapshot = build_monitoring_report_snapshot(
        generated_at=BASE_TIME,
        incident_evaluation=_empty_evaluation(),
        historical_notes=(
            "token=super-secret-token",
            "Authorization: Bearer abcdefgh123456789",
            "https://platform.example/health?token=super-secret-token#fragment",
            r"C:\Users\tra\PycharmProjects\monitoring-agent-0.8.1\.env",
            "private-run-12345",
        ),
    )

    rendered = "\n".join(
        [
            render_monitoring_report(snapshot),
            render_programming_agent_prompt(snapshot),
            redact_monitoring_text("api_key: abcdefgh123456789"),
        ]
    )

    assert "super-secret-token" not in rendered
    assert "abcdefgh123456789" not in rendered
    assert r"C:\Users\tra" not in rendered
    assert "private-run-12345" not in rendered
    assert "[redacted]" in rendered
    assert "[redacted-query]" in rendered
    assert "[redacted-windows-user-path]" in rendered
    assert "[redacted-private-id]" in rendered


def test_prompt_truncates_with_explicit_marker():
    snapshot = build_monitoring_report_snapshot(
        generated_at=BASE_TIME,
        incident_evaluation=_empty_evaluation(),
        hypotheses=tuple(f"hypothesis {index}" for index in range(50)),
    )

    prompt = render_programming_agent_prompt(snapshot, max_chars=180)

    assert prompt.startswith("DRAFT ONLY")
    assert len(prompt) <= 180
    assert "truncated: monitoring report exceeded configured character limit" in prompt
