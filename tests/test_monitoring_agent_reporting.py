def test_render_degraded_report_keeps_candidate_separate_from_incident():
    evaluation = evaluate_incident_lifecycle(
        [_cycle(1, payload_status={"system_database": "degraded"})]
    )
    snapshot = build_monitoring_report_snapshot(
        generated_at=BASE_TIME,
        incident_evaluation=evaluation,
        latest_heartbeat_status="degraded",
        observation_count=9,
        transport_failure_count=0,
    )

    report = render_monitoring_report(snapshot)

    assert "Summary status: degraded" in report
    assert (
        "- [warning] candidate endpoint:system_database: severity=warning, "
        "reason=endpoint_payload_status:degraded"
    ) in report
    assert "- [warning] suppressed endpoint:system_database: status=candidate" in report
    assert "delivery_enabled: false" in report


def test_render_incident_report_includes_outbox_intent_without_delivery(tmp_path):
    evaluation = evaluate_incident_lifecycle(
        [
            _cycle(1, payload_status={"system_database": "degraded"}),
            _cycle(2, payload_status={"system_database": "degraded"}),
        ]
    )
    store_snapshot = IncidentStateStore(tmp_path).apply_evaluation(
        evaluation,
        now=BASE_TIME,
    )
    snapshot = build_monitoring_report_snapshot(
        generated_at=BASE_TIME,
        incident_evaluation=evaluation,
        store_snapshot=store_snapshot,
        latest_heartbeat_status="degraded",
        observation_count=9,
        transport_failure_count=0,
    )

    report = render_monitoring_report(snapshot)

    assert "Summary status: incident" in report
    assert "- [warning] active endpoint:system_database:" in report
    assert "- [warning] opened endpoint:system_database: status=active" in report
    assert (
        "- [info] outbox_counts: pending=1, in_progress=0, sent=0, "
        "dead_letter=0"
    ) in report
    assert "- [info] pending opened endpoint:system_database:" in report
    assert "idempotency_key" not in report
    assert "Delivery disabled by design" in report


